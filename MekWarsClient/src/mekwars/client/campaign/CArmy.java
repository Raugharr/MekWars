package mekwars.client.campaign;

import jakarta.persistence.Table;

import mekwars.common.Army;
import mekwars.common.Unit;
import mekwars.common.composition.HasUnits;
import mekwars.common.util.TokenReader;

import java.text.DecimalFormat;
import java.text.NumberFormat;
import java.util.Collections;
import java.util.List;
import java.util.StringTokenizer;

/**
 * Client-side representation of an Army. The CArmy has, when compared to its server-side
 * counterpart, very few functional methods, and mostly serves as a holder for server data that the
 * client needs in order to represent forces graphically, load units into games, etc.
 */
@jakarta.persistence.Entity
@Table(name = "army")
public class CArmy extends Army {
    private HasUnits<CUnit> units = new HasUnits<>();

    /**
     * @see IHasUnits#getUnits
     */
    @Override
    public List<CUnit> getUnits() {
        return (List<CUnit>) Collections.unmodifiableList(units.getAll());
    }

    /**
     * @see IHasUnits#getUnit(int)
     */
    @Override
    public CUnit getUnit(int id) {
        return units.get(id);
    }

    /**
     * @see IHasUnits#addUnit(Unit, int)
     */
    @Override
    public void addUnit(int position, Unit unit) {
        unit.setArmy(this);
        units.add(position, (CUnit) unit);
    }

    /**
     * @see IHasUnits#addUnit(Unit)
     */
    @Override
    public void addUnit(Unit unit) {
        unit.setArmy(this);
        units.add((CUnit) unit);
    }

    /**
     * @see IHasUnits#removeUnit(int)
     */
    @Override
    public boolean removeUnit(int id) {
        CUnit unit = units.get(id);

        if (unit == null) {
            return false;
        }

        removeUnitFromC3Network(id);
        super.setBV(0);
        setRawForceSize(-1);
        
        unit.setOwner(null);
        units.remove(id);
        return true;
    }

    /**
     * @see IHasUnits#getUnitCount()
     */
    @Override
    public int getUnitCount() {
        return units.count();
    }

    /**
     * @see IHasUnits#countUnits(int, int)
     */
    @Override
    public int countUnits(int type, int weightClass) {
        return units.count(type, weightClass);
    }

    /**
     * @see IHasUnits#clear()
     */
    @Override
    public void clearUnits() {
        units.clear();
    }

    /**
     * Method that fills in Army data (common.Army value), given an informational String. Called
     * from CPlayer.setArmyData() and CPlayer.setData(). In both instances, the string being passed
     * is generated by the server and sent down using a PL| cmd.
     */
    public void fromString(String s, CPlayer p, String delimiter) {
        StringTokenizer ST = new StringTokenizer(s, delimiter);
        setId(TokenReader.readInt(ST));
        setBV(TokenReader.readInt(ST));
        setLocked(TokenReader.readBoolean(ST));
        setName(TokenReader.readString(ST));
        setLowerLimiter(TokenReader.readInt(ST));
        setUpperLimiter(TokenReader.readInt(ST));
        int count = TokenReader.readInt(ST);
        for (int i = 0; i < count; i++) {
            CUnit unit = p.getUnit(TokenReader.readInt(ST));

            // do not add units with id 0 as their id has already been replaced
            // --Torren
            if (unit.getId() != 0) {
                addUnit(unit);
            }
        }

        count = TokenReader.readInt(ST);
        for (int i = 0; i < count; i++) {
            int key = TokenReader.readInt(ST);
            int unit = TokenReader.readInt(ST);
            getC3Network().put(key, unit);
        }

        this.setOpForceSize(TokenReader.readFloat(ST));

        count = TokenReader.readInt(ST);
        for (int i = 0; i < count; i++) {
            int unit = TokenReader.readInt(ST);
            addCommander(unit);
        }

        boolean locked = TokenReader.readBoolean(ST);
        if (locked) {
            playerLockArmy();
        } else {
            playerUnlockArmy();
        }
        boolean disabled = TokenReader.readBoolean(ST);
        if (disabled) {
            disableArmy();
        } else {
            enableArmy();
        }
    }

    public String getSkillInfoForDisplay() {
        if (this.getUnits().size() < 1) {
            return " ";
        }

        String avgSkills = "0.0";
        String avgGunnery = "0.0";
        String avgPiloting = "0.0";
        int maxSkill = 0;
        int maxGunnery = 0;
        int maxPiloting = 0;
        int minSkill = 99;
        int minGunnery = 99;
        int minPiloting = 99;
        int numunits = 0;
        int totalGunnery = 0;
        int totalPiloting = 0;
        StringBuilder toReturn = new StringBuilder();
        for (Unit un : this.getUnits()) {
            CUnit unit = (CUnit) un;
            int gunnery = unit.getPilot().getGunnery();
            int piloting = unit.getPilot().getPiloting();
            maxSkill = Math.max(maxSkill, (gunnery + piloting));
            maxGunnery = Math.max(maxGunnery, gunnery);
            maxPiloting = Math.max(maxPiloting, piloting);
            minSkill = Math.min(minSkill, (gunnery + piloting));
            minGunnery = Math.min(minGunnery, gunnery);
            minPiloting = Math.min(minPiloting, piloting);
            totalGunnery += gunnery;
            totalPiloting += piloting;
            numunits++;
        }
        // Need to use a DecimalFormat so we don't get just whole integer averages

        double avgS = (double) (totalGunnery + totalPiloting) / (double) numunits;
        double avgG = (double) (totalGunnery) / (double) numunits;
        double avgP = (double) (totalPiloting) / (double) numunits;
        DecimalFormat twoDForm = (DecimalFormat) NumberFormat.getNumberInstance();
        twoDForm.applyPattern("0.00");

        avgSkills = twoDForm.format(avgS);
        avgGunnery = twoDForm.format(avgG);
        avgPiloting = twoDForm.format(avgP);

        toReturn.append("<html><table><tr><td colspan=4>Skillsums</td></tr>");
        toReturn.append("<tr><td>&nbsp;</td><td>Total</td><td>Gunnery</td><td>Piloting</td></tr>");
        toReturn.append(
                "<tr><td>Average:</td><td>"
                        + avgSkills
                        + "</td><td>"
                        + avgGunnery
                        + "</td><td>"
                        + avgPiloting
                        + "</td></tr>");
        toReturn.append(
                "<tr><td>Maximum:</td><td>"
                        + maxSkill
                        + "</td><td>"
                        + maxGunnery
                        + "</td><td>"
                        + maxPiloting
                        + "</td></tr>");
        toReturn.append(
                "<tr><td>Minimum:</td><td>"
                        + minSkill
                        + "</td><td>"
                        + minGunnery
                        + "</td><td>"
                        + minPiloting
                        + "</td></tr>");
        toReturn.append("</table></html>");
        return toReturn.toString();
    }
}
